"""PAT model inputs as database rows → out/pat/db_inputs.sql (NOT applied; needs AB's OK) and out/pat/facts_review.md.

    python3 -m src.extract.pl_angel > out/pat/facts_angel_pl.json
    python3 -m src.extract.pl_groww > out/pat/facts_groww_pl.json
    python3 seed/build_pat_db_rows.py

Adds sb_assumptions rows (key prefix pat_, from seed/pat_assumptions.json) and sb_disclosure_facts rows for the filed
quarterly P&L lines and shares outstanding (segment 'consolidated', extracted_by 'claude', status 'staged'). Staged
facts are not used by a live run until reviewed (status 'reviewed'), as for every other filing fact.
Idempotent: running the SQL twice adds nothing. Changes no existing row.
Full-year rows (Angel One's FY 2025 / FY 2026 totals) are left out: sb_disclosure_facts takes period_type M or Q
only, and the model reads quarters. The FY 2026 figures behind the derived Q3 FY 2026 rows stay in those rows' notes.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'out/pat'


def facts():
    rows = []
    for name in ('angel', 'groww'):
        d = json.loads((OUT / f'facts_{name}_pl.json').read_text())
        if d['conflicts']:
            raise SystemExit(f'{name}: unresolved conflicts between filings: {d["conflicts"]}')
        for f in d['facts'] + [d['shares']]:
            if f['period_type'] == 'FY':
                continue     # the table takes M / Q only; see the module docstring
            rows.append(dict(broker_id=f['broker_id'], period_type=f['period_type'] or 'Q', period_key=f['period_key'] or '',
                             metric=f['metric'], segment=f['segment'], value=f['value'], unit=f['unit'],
                             table_label=f['table_label'], source_ref=f['source_ref'], extracted_by='claude',
                             status='staged', note=f.get('note')))
    return rows


def sql(assumptions, fact_rows):
    j = lambda rows: json.dumps(rows, indent=0, ensure_ascii=False)
    return f"""-- PAT model inputs (generated by seed/build_pat_db_rows.py; NOT applied). Needs AB's OK.
-- Adds: {len(assumptions)} sb_assumptions (key prefix pat_) and {len(fact_rows)} sb_disclosure_facts
-- (segment 'consolidated', extracted_by 'claude', status 'staged'): the filed quarterly P&L lines of Angel One
-- (investor presentations) and Groww (results statements), and shares outstanding. Review: out/pat/facts_review.md.
-- Idempotent: running it twice adds nothing. Changes no existing row.

begin;

insert into public.sb_assumptions (broker_id, key, value, value_text, unit, source_ref, note)
select x.broker_id, x.key, x.value, x.value_text, x.unit, x.source_ref, x.note
from jsonb_to_recordset($json${j(assumptions)}$json$::jsonb)
  as x(broker_id text, key text, value numeric, value_text text, unit text, source_ref text, note text)
where not exists (select 1 from public.sb_assumptions a where a.broker_id = x.broker_id and a.key = x.key);

insert into public.sb_disclosure_facts (broker_id, period_type, period_key, metric, segment, value, unit,
                                        table_label, source_ref, extracted_by, status, note)
select x.broker_id, x.period_type, x.period_key, x.metric, x.segment, x.value, x.unit, x.table_label,
       x.source_ref, x.extracted_by, x.status, x.note
from jsonb_to_recordset($json${j(fact_rows)}$json$::jsonb)
  as x(broker_id text, period_type text, period_key text, metric text, segment text, value numeric, unit text,
       table_label text, source_ref text, extracted_by text, status text, note text)
where not exists (select 1 from public.sb_disclosure_facts f
                  where f.broker_id = x.broker_id and f.metric = x.metric and f.period_key = x.period_key
                    and f.segment = x.segment and f.source_ref = x.source_ref);

commit;

-- Check after applying (expect {len(assumptions)} / {len(fact_rows)} on a first run):
--   select (select count(*) from sb_assumptions where key like 'pat_%') as assumptions,
--          (select count(*) from sb_disclosure_facts where segment = 'consolidated' and extracted_by = 'claude') as facts;
-- Rollback: delete from sb_disclosure_facts where segment = 'consolidated' and extracted_by = 'claude'
--             and (metric like 'pl_%' or metric in ('trading_days', 'shares_outstanding_cr'));
--           delete from sb_assumptions where key like 'pat_%';
"""


def review_md(fact_rows):
    L = ['# PAT model: staged facts to review', '',
         'Each row is one filed figure as printed (unit as filed). Tick it off against the page in `source_ref`; '
         'reviewed rows get status `reviewed`. Rows marked [DERIVED] show their arithmetic in the note.', '',
         '| Broker | Period | Metric | Value | Unit | Source | Note |', '|---|---|---|---:|---|---|---|']
    for f in sorted(fact_rows, key=lambda r: (r['broker_id'], r['metric'], r['period_key'])):
        L.append(f"| {f['broker_id']} | {f['period_key']} | {f['metric']} | {f['value']:,.2f} | {f['unit']} | "
                 f"`{f['source_ref']}` | {f.get('note') or ''} |")
    return '\n'.join(L) + '\n'


def main():
    assumptions = [dict(a, value_text=a.get('value_text')) for a in json.loads((ROOT / 'seed/pat_assumptions.json').read_text())['assumptions']]
    rows = facts()
    (OUT / 'db_inputs.sql').write_text(sql(assumptions, rows))
    (OUT / 'facts_review.md').write_text(review_md(rows))
    print(f'{len(assumptions)} assumptions, {len(rows)} facts → out/pat/db_inputs.sql, out/pat/facts_review.md')


if __name__ == '__main__':
    main()
