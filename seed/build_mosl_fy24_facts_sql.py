"""The 116 MOSL FY24 facts as database rows, status 'reviewed' (nothing is written to the database here).

    python3 seed/build_mosl_fy24_facts_sql.py        # writes out/mosl/fy24_facts.sql

NOT APPLIED. For after AB approves switch m-g and the 116 candidate facts (docs/MOSL_LIVE_SPEC.md, "Proposed switch m-g").
Source: out/mosl/facts_candidates_fy24.json (Q4 FY26 data book, the latest vintage that carries FY24).

The SQL is insert-only and idempotent:
  - sb_documents: the data book(s) the facts cite are inserted where no MOSL row with the same sha256 exists (doc_id is a uuid5 of the
    sha256, so a second run computes the same id and adds nothing). doc_type 'data_book', period_key = the book's quarter, file_path
    in the raw-disclosures layout used for the other brokers' documents.
  - sb_disclosure_facts: a fact is inserted only where no row with the same (broker, metric, period_key, segment, source_ref) exists;
    broker MOSL, extracted_by 'claude', status 'reviewed', reviewed_at = the time the script runs, doc_id looked up by sha256;
    fact_id comes from the table's sequence. No existing row (the 290 reviewed facts, ids 846-1135, or the seed rows) is changed.
"""
import json
import os
import re
import uuid

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
SRC = os.path.join(ROOT, 'out', 'mosl', 'facts_candidates_fy24.json')
OUT = os.path.join(ROOT, 'out', 'mosl', 'fy24_facts.sql')
UUID_NS = uuid.UUID('6ba7b811-9dad-11d1-80b4-00c04fd430c8')      # uuid.NAMESPACE_URL
FILE_DIR = 'broker_db/data/raw/disclosures/mosl/'

DOC_COLS = ('doc_id', 'broker_id', 'doc_type', 'period_key', 'title', 'url', 'file_path', 'sha256', 'published_at', 'note')
FACT_COLS = ('broker_id', 'period_type', 'period_key', 'metric', 'segment', 'value', 'unit', 'sha256', 'page', 'table_label',
             'source_ref', 'extracted_by', 'note')


def _quarter(period):
    """'Q4 FY26 (qtr ended 2026-03-31)' -> 'Q4 FY 2026'."""
    m = re.match(r'Q(\d) FY(\d\d)', period)
    return f'Q{m.group(1)} FY 20{m.group(2)}'


def rows(cand=None):
    cand = cand or json.load(open(SRC))
    docs = []
    for fname, d in sorted(cand['documents'].items()):
        docs.append(dict(doc_id=str(uuid.uuid5(UUID_NS, d['sha256'])), broker_id='MOSL', doc_type=d['doc_type'],
                         period_key=_quarter(d['period']),
                         title=f"Motilal Oswal {d['period'].split(' (')[0]} data book",
                         url=d['url'], file_path=FILE_DIR + fname, sha256=d['sha256'],
                         published_at=f"{d['filing_date']}T00:00:00+05:30",
                         note='registered for the FY24 facts (switch m-g); sha256 of the file read'))
    facts = []
    for c in cand['sb_disclosure_facts']:
        fname = c['source_ref'].split(':', 1)[1].split('#')[0]
        r = {k: c.get(k) for k in FACT_COLS if k != 'sha256'}
        r['segment'] = c.get('segment') or ''
        r['sha256'] = cand['documents'][fname]['sha256']
        r['extracted_by'] = c.get('extracted_by') or 'claude'
        facts.append(r)
    return docs, facts


def sql(docs, facts):
    j = lambda x: json.dumps(x, ensure_ascii=False, indent=0)
    L = ['-- MOSL FY24 facts (switch m-g) as database rows, status reviewed (generated by seed/build_mosl_fy24_facts_sql.py; NOT applied).',
         "-- For AFTER AB approves switch m-g and these 116 candidate facts (out/mosl/facts_candidates_fy24.json, Q4 FY26 data book).",
         '-- Insert-only and idempotent: running it twice adds nothing; no existing row is changed (the 290 reviewed MOSL facts,',
         '-- ids 846-1135, and the workbook seed rows are not touched).',
         f"-- Adds: {len(docs)} sb_documents (where no MOSL document has the same sha256), {len(facts)} sb_disclosure_facts",
         "-- (broker MOSL, extracted_by 'claude', status 'reviewed', reviewed_at = now()); doc_id is looked up by sha256.",
         "-- Then the live default stays m-abcdef until m-g is switched on in src/live/mosl_run.py (SWITCHES) by a separate commit.",
         '', 'begin;', '',
         'insert into public.sb_documents (doc_id, broker_id, doc_type, period_key, title, url, file_path, sha256, published_at, fetched_at, note)',
         'select x.doc_id::uuid, x.broker_id, x.doc_type, x.period_key, x.title, x.url, x.file_path, x.sha256,',
         '       x.published_at::timestamptz, now(), x.note',
         f'from jsonb_to_recordset($json${j(docs)}$json$::jsonb)',
         '  as x(doc_id text, broker_id text, doc_type text, period_key text, title text, url text, file_path text, sha256 text,',
         '       published_at text, note text)',
         "where not exists (select 1 from public.sb_documents d where d.broker_id = 'MOSL' and d.sha256 = x.sha256);", '',
         'insert into public.sb_disclosure_facts (broker_id, period_type, period_key, metric, segment, value, unit, doc_id, page,',
         '                                        table_label, source_ref, extracted_by, status, reviewed_at, note)',
         "select x.broker_id, x.period_type, x.period_key, x.metric, x.segment, x.value, x.unit, d.doc_id, x.page,",
         "       x.table_label, x.source_ref, x.extracted_by, 'reviewed', now(), x.note",
         f'from jsonb_to_recordset($json${j(facts)}$json$::jsonb)',
         '  as x(broker_id text, period_type text, period_key text, metric text, segment text, value numeric, unit text, sha256 text,',
         '       page text, table_label text, source_ref text, extracted_by text, note text)',
         "join public.sb_documents d on d.broker_id = 'MOSL' and d.sha256 = x.sha256",
         'where not exists (select 1 from public.sb_disclosure_facts f',
         '                  where f.broker_id = x.broker_id and f.metric = x.metric and f.period_key = x.period_key',
         '                    and f.segment = x.segment and f.source_ref = x.source_ref);', '',
         'commit;', '',
         f"-- Check after applying (expect {len(facts)} on a first run, 0 new rows on a second):",
         "--   select count(*) from sb_disclosure_facts where broker_id='MOSL' and period_key like '% FY 2024' and status='reviewed';",
         "-- Rollback: delete from sb_disclosure_facts where broker_id='MOSL' and period_key like '% FY 2024' and extracted_by='claude';",
         "--           delete from sb_documents where broker_id='MOSL' and note like 'registered for the FY24 facts%';", '']
    return '\n'.join(L)


if __name__ == '__main__':
    docs, facts = rows()
    with open(OUT, 'w') as fh:
        fh.write(sql(docs, facts))
    print(f'written {os.path.relpath(OUT)}: {len(docs)} documents, {len(facts)} facts')
