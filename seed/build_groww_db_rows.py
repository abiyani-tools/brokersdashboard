"""Rows for AB to approve: Groww's workbook inputs as database rows (nothing is written to the database here).

    python3 seed/build_groww_db_rows.py            # writes out/groww/db_inputs.json and out/groww/db_inputs.sql

Source: snapshot/groww_snapshot_2026-10-23.json (41 workbook seed facts, 14 assumptions, 10 pins; all broker_id GROWW).
The daily live run reads these from the database exactly as Angel One's are read (477 seed facts, 15 assumptions, 28 pins):
a Groww run from the DB is refused until they exist. The 103 filing facts (fact_id 702-804) are already staged and
need AB's review separately (out/groww/facts_review.md); this script does not touch them.

The SQL is idempotent: assumptions and pins insert on conflict do nothing; seed facts insert only where no row with the
same (broker, metric, period, segment, source_ref) exists. Seed facts are extracted_by 'excel_seed', status 'staged'
(as Angel One's); fact_id comes from the table's sequence.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
SNAP = os.path.join(ROOT, 'snapshot', 'groww_snapshot_2026-10-23.json')
OUT = os.path.join(ROOT, 'out', 'groww')

ASSUMPTION_COLS = ('broker_id', 'key', 'value', 'value_text', 'unit', 'source_ref', 'note')
PIN_COLS = ('broker_id', 'key', 'period_key', 'value', 'value_text', 'excel_cell', 'note')
FACT_COLS = ('broker_id', 'period_type', 'period_key', 'metric', 'segment', 'value', 'unit', 'table_label',
             'source_ref', 'extracted_by', 'status', 'note')


def rows(snap=None):
    snap = snap or json.load(open(SNAP))
    assert snap['broker_id'] == 'GROWW'
    pick = lambda r, cols: {c: r.get(c) for c in cols}
    return {
        'sb_assumptions': [pick(a, ASSUMPTION_COLS) for a in snap['assumptions']],
        'sb_parity_pins': [pick(dict(p, period_key=p.get('period_key') or ''), PIN_COLS) for p in snap['pins']],
        'sb_disclosure_facts': [pick(dict(f, segment=f.get('segment') or '', extracted_by='excel_seed',
                                          status='staged'), FACT_COLS) for f in snap['facts']],
    }


def sql(r):
    j = lambda name: json.dumps(r[name], ensure_ascii=False, indent=0)
    L = ['-- Groww workbook inputs as database rows (generated by seed/build_groww_db_rows.py; NOT applied).',
         '-- Needs AB\'s OK. Same rows as out/groww/db_inputs.json. Idempotent: running it twice adds nothing.',
         f"-- Adds: {len(r['sb_assumptions'])} sb_assumptions, {len(r['sb_parity_pins'])} sb_parity_pins, "
         f"{len(r['sb_disclosure_facts'])} sb_disclosure_facts (extracted_by 'excel_seed', status 'staged'), broker_id 'GROWW'.",
         '-- Changes no existing row. Facts 702-804 (the filing facts) are not touched; they are reviewed separately.',
         '-- Until this runs and facts 702-804 are reviewed, `run_live.py --db --broker GROWW` refuses with a clear message',
         '-- and `--broker all` still publishes Angel One (warning only).', '',
         'begin;', '',
         'insert into public.sb_assumptions (broker_id, key, value, value_text, unit, source_ref, note)',
         'select x.broker_id, x.key, x.value, x.value_text, x.unit, x.source_ref, x.note',
         f"from jsonb_to_recordset($json${j('sb_assumptions')}$json$::jsonb)",
         '  as x(broker_id text, key text, value numeric, value_text text, unit text, source_ref text, note text)',
         'on conflict (broker_id, key) do nothing;', '',
         'insert into public.sb_parity_pins (broker_id, key, period_key, value, value_text, excel_cell, note)',
         'select x.broker_id, x.key, x.period_key, x.value, x.value_text, x.excel_cell, x.note',
         f"from jsonb_to_recordset($json${j('sb_parity_pins')}$json$::jsonb)",
         '  as x(broker_id text, key text, period_key text, value numeric, value_text text, excel_cell text, note text)',
         'on conflict (broker_id, key, period_key) do nothing;', '',
         'insert into public.sb_disclosure_facts (broker_id, period_type, period_key, metric, segment, value, unit,',
         '                                        table_label, source_ref, extracted_by, status, note)',
         'select x.broker_id, x.period_type, x.period_key, x.metric, x.segment, x.value, x.unit, x.table_label,',
         '       x.source_ref, x.extracted_by, x.status, x.note',
         f"from jsonb_to_recordset($json${j('sb_disclosure_facts')}$json$::jsonb)",
         '  as x(broker_id text, period_type text, period_key text, metric text, segment text, value numeric, unit text,',
         '       table_label text, source_ref text, extracted_by text, status text, note text)',
         'where not exists (select 1 from public.sb_disclosure_facts f',
         '                  where f.broker_id = x.broker_id and f.metric = x.metric and f.period_key = x.period_key',
         '                    and f.segment = x.segment and f.source_ref = x.source_ref);', '',
         'commit;', '',
         '-- Check after applying (expect 14 / 10 / 41 on a first run):',
         "--   select (select count(*) from sb_assumptions where broker_id='GROWW') as assumptions,",
         "--          (select count(*) from sb_parity_pins where broker_id='GROWW') as pins,",
         "--          (select count(*) from sb_disclosure_facts where broker_id='GROWW' and extracted_by='excel_seed') as seed_facts;",
         '-- Rollback: delete from sb_disclosure_facts where broker_id=\'GROWW\' and extracted_by=\'excel_seed\';',
         "--           delete from sb_parity_pins where broker_id='GROWW'; delete from sb_assumptions where broker_id='GROWW';", '']
    return '\n'.join(L)


if __name__ == '__main__':
    r = rows()
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, 'db_inputs.json'), 'w') as fh:
        json.dump(r, fh, indent=1, ensure_ascii=False)
        fh.write('\n')
    with open(os.path.join(OUT, 'db_inputs.sql'), 'w') as fh:
        fh.write(sql(r))
    print({k: len(v) for k, v in r.items()}, 'written out/groww/db_inputs.json, out/groww/db_inputs.sql')
